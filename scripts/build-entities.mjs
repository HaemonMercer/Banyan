// Generates src/markdown/entities.ts (HTML5 named character references) from the `entities` package.
// Run: node scripts/build-entities.mjs
import { readFileSync, writeFileSync } from "node:fs";

const map = JSON.parse(readFileSync(new URL("../node_modules/entities/lib/maps/entities.json", import.meta.url), "utf8"));
const lines = Object.keys(map)
    .sort()
    .map((k) => `    ${JSON.stringify(k)}: ${JSON.stringify(map[k])},`);
const out = `// Generated by scripts/build-entities.mjs — do not edit.
/** HTML5 named character references (without \`&\` and \`;\`). */
export const ENTITIES: Record<string, string> = {
${lines.join("\n")}
};
`;
writeFileSync(new URL("../src/markdown/entities.ts", import.meta.url), out);
console.log(`wrote ${Object.keys(map).length} entities`);
